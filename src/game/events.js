/** 효과 튜플 → 사람이 읽는 칩 문구 + 좋고 나쁨 */
export function fxChip(f, itemName = (id) => id) {
  const [k, v, a, b] = f;
  if (k === 'funds') return { t: `자금 ${SIGN(v)} CR`, good: v > 0 };
  if (k === 'rep') return { t: `평판 ${SIGN(v)}`, good: v > 0 };
  if (k === 'mor') return { t: `${SC[a || 'dept']} 사기 ${SIGN(v)}`, good: v > 0 };
  if (k === 'hp') return { t: `${SC[a || 'dept']} HP ${SIGN(v)}`, good: v > 0 };
  if (k === 'item') return { t: `${itemName(v)} ×${a || 1}`, good: true };
  if (k === 'research') return { t: `연구 포인트 ${SIGN(v)}`, good: v > 0 };
  if (k === 'aff') return { t: `팀장 친밀도 ${SIGN(v)}`, good: v > 0 };
  if (k === 'snow') return { t: `적설 ${SIGN(v)}%`, good: v < 0 };
  if (k === 'buff') return { t: `오늘 하루 「${a}」`, good: Object.values(v).every((x) => (typeof x === 'boolean' ? true : x >= 0)) || Object.entries(v).reduce((s, [kk, x]) => s + (kk === 'dmg' ? -x : x), 0) > 0 };
  return { t: String(k), good: true };
}
